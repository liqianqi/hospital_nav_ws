#!/usr/bin/python3
"""由 nav_ws/src/nav_bringup/urdf/chassis.urdf (onshape-to-robot 导出) 生成仿真用底盘 xacro。

  - mesh 路径改到 package://omni_sim_description/meshes, 中文文件名换成 ASCII
  - 去掉所有 mesh 碰撞体(几十个 STL 碰撞体仿真很慢), 换成:
      底盘 box + 中间立杆 cylinder + 每个轮子一个零摩擦 sphere (支撑车体)
    底盘由 gz VelocityControl 直接给 body 水平速度 (理想全向运动), 轮子只做外观/关节动画.
    零摩擦由 urdf_to_sim_sdf.py 在生成 SDF 时写入 (URDF 的 <mu1>/<mu2> 扩展对这些碰撞体不生效).
  - 输出 urdf/chassis.urdf.xacro, 由 robot.urdf.xacro include

用法: python3 make_sim_chassis.py <chassis.urdf> <meshes_dir> <out.xacro>
"""
import os
import sys
import xml.etree.ElementTree as ET

RENAME = {
    '超声波传感器': 'ultrasonic',
    '6寸全向轮': 'omni6in',
    '中管': 'mid_tube',
    '外管': 'outer_tube',
}

WHEEL_R = 0.075



def ascii_name(name):
    for k, v in RENAME.items():
        name = name.replace(k, v)
    return name


def main():
    src, mesh_dir, dst = sys.argv[1:4]
    for f in os.listdir(mesh_dir):
        new = ascii_name(f)
        if new != f:
            os.rename(os.path.join(mesh_dir, f), os.path.join(mesh_dir, new))

    root = ET.parse(src).getroot()
    out = ET.Element('robot', {'xmlns:xacro': 'http://www.ros.org/wiki/xacro'})

    for el in root:
        if el.tag == 'link':
            el.set('name', ascii_name(el.get('name')))
        if el.tag == 'joint':
            for tag in ('parent', 'child'):
                e = el.find(tag)
                e.set('link', ascii_name(e.get('link')))
        if el.tag == 'link':
            for col in el.findall('collision'):
                el.remove(col)
            for vis in el.findall('visual'):
                m = vis.find('geometry/mesh')
                fn = m.get('filename').replace('package://nav_bringup', 'package://omni_sim_description')
                m.set('filename', ascii_name(fn))
                mat = vis.find('material')
                if mat is not None:
                    mat.set('name', ascii_name(mat.get('name')))
            name = el.get('name')
            if name == 'updownbase_urdf_asm':
                # 底盘本体 + 立杆 (updownbase 与 base_link 只差 yaw=pi, 对称形状不受影响)
                el.append(ET.fromstring(
                    '<collision name="chassis_box"><origin xyz="0 0 0.125"/>'
                    '<geometry><box size="0.50 0.50 0.19"/></geometry></collision>'))
                el.append(ET.fromstring(
                    '<collision name="pole"><origin xyz="0 0 0.33"/>'
                    '<geometry><cylinder radius="0.06" length="0.40"/></geometry></collision>'))
        out.append(el)

    for el in list(out.findall('link')):
        name = el.get('name')
        if 'omni6in' in name:
            el.append(ET.fromstring(
                f'<collision name="wheel"><geometry><sphere radius="{WHEEL_R}"/></geometry></collision>'))

    ET.indent(out, space='  ')
    body = ET.tostring(out, encoding='unicode')
    with open(dst, 'w') as f:
        f.write('<?xml version="1.0"?>\n<!-- AUTO-GENERATED by scripts/make_sim_chassis.py from nav_ws chassis.urdf -->\n')
        f.write(body + '\n')
    print('wrote', dst)


if __name__ == '__main__':
    main()
